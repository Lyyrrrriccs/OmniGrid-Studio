function normalizeHueConfig(raw = {}) {
  const src = raw && typeof raw === 'object' ? raw : {};
  return {
    ...DEFAULT_HUE_CONFIG,
    ...src,
    selectedLights: Array.isArray(src.selectedLights) ? src.selectedLights.map(String) : [],
    eventScenes: { ...DEFAULT_HUE_CONFIG.eventScenes, ...(src.eventScenes || {}) }
  };
}

function cleanLanIp(raw) {
  const s = String(raw || '').trim().replace(/^https?:\/\//i, '').replace(/\/.*$/, '').split(':')[0];
  return /^\d{1,3}(\.\d{1,3}){3}$/.test(s) ? s : '';
}

function hueRequest(bridgeIp, urlPath, method = 'GET', bodyObj = null, timeoutMs = 2000, useHttps = false) {
  return new Promise((resolve, reject) => {
    const host = cleanLanIp(bridgeIp);
    if (!host) return reject(new Error('Ungültige lokale Hue Bridge IP-Adresse.'));
    const payload = bodyObj ? Buffer.from(JSON.stringify(bodyObj), 'utf8') : null;
    const transport = useHttps ? https : http;
    const opts = {
      host,
      port: useHttps ? 443 : 80,
      path: urlPath,
      method,
      timeout: timeoutMs,
      ...(useHttps ? { rejectUnauthorized: false } : {}),
      headers: payload
        ? { 'Content-Type': 'application/json', 'Content-Length': payload.length }
        : { Accept: 'application/json' }
    };

    const req = transport.request(opts, (res) => {
      let data = '';
      res.on('data', (c) => { data += c; });
      res.on('end', () => {
        if (res.statusCode < 200 || res.statusCode >= 300) {
          return reject(new Error(`Hue HTTP ${res.statusCode}`));
        }
        try {
          resolve(JSON.parse(data));
        } catch (e) {
          reject(e);
        }
      });
    });
    req.on('error', (err) => {
      if (!useHttps) {
        hueRequest(bridgeIp, urlPath, method, bodyObj, timeoutMs, true).then(resolve).catch(() => reject(err));
      } else {
        reject(err);
      }
    });
    req.on('timeout', () => req.destroy(new Error('Hue Timeout')));
    if (payload) req.write(payload);
    req.end();
  });
}

function ssdpDiscoverHue(timeoutMs = 1100) {
  return new Promise((resolve) => {
    const foundIps = new Set();
    let sock = null;
    try {
      sock = dgram.createSocket({ type: 'udp4', reuseAddr: true });
      sock.on('message', (msg, rinfo) => {
        const txt = msg.toString('utf8');
        if (/hue-bridgeid|IpBridge/i.test(txt) && rinfo?.address) {
          foundIps.add(rinfo.address);
        }
      });
      sock.on('error', () => {});
      sock.bind(() => {
        const pkt = Buffer.from(
          'M-SEARCH * HTTP/1.1\r\nHOST: 239.255.255.250:1900\r\nMAN: "ssdp:discover"\r\nMX: 1\r\nST: upnp:rootdevice\r\n\r\n',
          'utf8'
        );
        sock.send(pkt, 0, pkt.length, 1900, '239.255.255.250', () => {});
      });
    } catch (e) {}
    setTimeout(() => {
      try { sock?.close(); } catch (e) {}
      resolve([...foundIps]);
    }, timeoutMs);
  });
}

async function probeHueBridge(ip, timeoutMs = 650) {
  try {
    const cfg = await hueRequest(ip, '/api/0/config', 'GET', null, timeoutMs);
    if (cfg && (cfg.bridgeid || /hue/i.test(`${cfg.name || ''} ${cfg.modelid || ''}`))) {
      return {
        ip,
        name: cfg.name || `Philips Hue (${ip})`,
        bridgeId: cfg.bridgeid || '',
        modelId: cfg.modelid || ''
      };
    }
  } catch (e) {}
  return null;
}

async function discoverHueBridges() {
  const foundMap = new Map();
  const ssdpIps = await ssdpDiscoverHue(1000);
  for (const ip of ssdpIps) {
    const info = await probeHueBridge(ip, 1200);
    if (info) foundMap.set(ip, info);
  }
  if (foundMap.size > 0) return [...foundMap.values()];

  // Fallback: Fast local subnet scan (100% offline LAN, zero cloud)
  const nets = os.networkInterfaces();
  const prefixes = new Set();
  for (const list of Object.values(nets)) {
    for (const iface of list || []) {
      if (iface.family === 'IPv4' && !iface.internal && iface.address) {
        const p = iface.address.split('.');
        if (p.length === 4) prefixes.add(`${p[0]}.${p[1]}.${p[2]}`);
      }
    }
  }
  const candidates = [];
  for (const pref of prefixes) {
    for (let i = 1; i <= 254; i++) candidates.push(`${pref}.${i}`);
  }
  const batchSize = 64;
  for (let i = 0; i < candidates.length; i += batchSize) {
    const res = await Promise.all(candidates.slice(i, i + batchSize).map((ip) => probeHueBridge(ip, 550)));
    for (const b of res) {
      if (b) foundMap.set(b.ip, b);
    }
  }
  return [...foundMap.values()];
}

async function pairHueBridge(bridgeIp) {
  const ip = cleanLanIp(bridgeIp);
  if (!ip) return { ok: false, error: 'Bitte zuerst die lokale IP-Adresse der Hue Bridge eingeben oder suchen.' };
  const res = await hueRequest(ip, '/api', 'POST', { devicetype: 'omnigrid_studio#desktop' }, 2500);
  const first = Array.isArray(res) ? res[0] : res;
  if (first?.error) {
    if (Number(first.error.type) === 101) {
      return {
        ok: false,
        needsLinkButton: true,
        error: 'Bitte drücke jetzt den runden Link-Knopf auf deiner Philips Hue Bridge und klicke innerhalb von 30 Sek. erneut auf „Koppeln“!'
      };
    }
    return { ok: false, error: first.error.description || 'Hue Kopplung fehlgeschlagen.' };
  }
  const username = first?.success?.username;
  if (!username) return { ok: false, error: 'Kein App-Key von der Hue Bridge erhalten.' };
  return { ok: true, bridgeIp: ip, username };
}

function hexToHueHsb(hex) {
  const clean = String(hex || '#ffffff').replace(/^#/, '').trim();
  const num = parseInt(clean, 16);
  const r = ((Number.isNaN(num) ? 0xffffff : num) >> 16) & 255;
  const g = ((Number.isNaN(num) ? 0xffffff : num) >> 8) & 255;
  const b = (Number.isNaN(num) ? 0xffffff : num) & 255;

  const rf = r / 255;
  const gf = g / 255;
  const bf = b / 255;
  const max = Math.max(rf, gf, bf);
  const min = Math.min(rf, gf, bf);
  const d = max - min;
  let h = 0;
  if (d !== 0) {
    if (max === rf) h = ((gf - bf) / d) % 6;
    else if (max === gf) h = (bf - rf) / d + 2;
    else h = (rf - gf) / d + 4;
    h = Math.round(h * 60);
    if (h < 0) h += 360;
  }
  const s = max === 0 ? 0 : d / max;
  return {
    hue: Math.max(0, Math.min(65535, Math.round((h / 360) * 65535))),
    sat: Math.max(0, Math.min(254, Math.round(s * 254))),
    bri: Math.max(1, Math.min(254, Math.round(max * 254)))
  };
}

async function listHueResources(bridgeIp, username) {
  const ip = cleanLanIp(bridgeIp);
  const key = String(username || '').trim();
  if (!ip || !key) throw new Error('Hue Bridge IP und lokaler Kopplungs-Key erforderlich.');

  const [lightsObj, scenesObj, groupsObj] = await Promise.all([
    hueRequest(ip, `/api/${encodeURIComponent(key)}/lights`, 'GET'),
    hueRequest(ip, `/api/${encodeURIComponent(key)}/scenes`, 'GET').catch(() => ({})),
    hueRequest(ip, `/api/${encodeURIComponent(key)}/groups`, 'GET').catch(() => ({}))
  ]);

  if (Array.isArray(lightsObj) && lightsObj[0]?.error) {
    throw new Error(lightsObj[0].error.description || 'Hue Zugriff verweigert (bitte neu koppeln).');
  }

  const lights = Object.entries(lightsObj || {}).map(([id, l]) => ({
    id: String(id),
    name: l?.name || `Hue Lampe ${id}`,
    type: l?.productname || l?.type || 'Hue Light',
    on: Boolean(l?.state?.on),
    bri: Math.round(((Number(l?.state?.bri ?? 200)) / 254) * 100),
    reachable: l?.state?.reachable !== false
  }));

  const groupNames = {};
  for (const [gid, g] of Object.entries(groupsObj || {})) {
    groupNames[gid] = g?.name || `Gruppe ${gid}`;
  }

  const hueScenes = Object.entries(scenesObj || {})
    .filter(([, sc]) => sc && sc.name)
    .map(([sid, sc]) => {
      const gid = String(sc.group || '0');
      const gLabel = sc.group && groupNames[gid] ? ` (${groupNames[gid]})` : '';
      return {
        id: `scene:${sid}:${gid}`,
        name: `🌈 Hue-Szene: ${sc.name}${gLabel}`
      };
    })
    .sort((a, b) => a.name.localeCompare(b.name));

  return {
    ok: true,
    lights,
    actions: [...hueScenes, ...HUE_PRESET_ACTIONS]
  };
}

function resolveHueLightIds(lightsObj, selectedIds = []) {
  const allIds = Object.keys(lightsObj || {});
  if (!Array.isArray(selectedIds) || !selectedIds.length) return allIds;
  const filtered = allIds.filter((id) => selectedIds.includes(String(id)));
  return filtered.length ? filtered : allIds;
}

async function setHueLights({ bridgeIp, username, selectedLights = [], on, brightness, hexColor }) {
  const ip = cleanLanIp(bridgeIp);
  const key = String(username || '').trim();
  if (!ip || !key) return { ok: false, error: 'Hue Bridge ist noch nicht gekoppelt.' };

  const lightsObj = await hueRequest(ip, `/api/${encodeURIComponent(key)}/lights`, 'GET');
  const ids = resolveHueLightIds(lightsObj, selectedLights);
  if (!ids.length) return { ok: false, error: 'Keine Hue-Lampen auf der Bridge gefunden.' };

  const patch = {};
  if (typeof on === 'boolean') patch.on = on;
  if (hexColor && patch.on !== false) {
    const hsb = hexToHueHsb(hexColor);
    patch.on = true;
    patch.hue = hsb.hue;
    patch.sat = hsb.sat;
    patch.bri = hsb.bri;
  }
  if (typeof brightness === 'number' && patch.on !== false) {
    patch.bri = Math.max(1, Math.min(254, Math.round((brightness / 100) * 254)));
  }

  let updated = 0;
  await Promise.all(
    ids.map(async (id) => {
      try {
        await hueRequest(ip, `/api/${encodeURIComponent(key)}/lights/${id}/state`, 'PUT', patch, 2000);
        updated++;
      } catch (e) {}
    })
  );
  return { ok: updated > 0, updatedCount: updated };
}

async function applyHueAction(hueCfg, actionId) {
  const ip = cleanLanIp(hueCfg?.bridgeIp);
  const key = String(hueCfg?.username || '').trim();
  const act = String(actionId || '').trim();
  if (!ip || !key || !act) return { ok: false, error: 'Hue Bridge oder Aktion fehlt.' };

  if (act.startsWith('scene:')) {
    const [, sceneId, groupId] = act.split(':');
    const gid = groupId || '0';
    await hueRequest(ip, `/api/${encodeURIComponent(key)}/groups/${encodeURIComponent(gid)}/action`, 'PUT', {
      on: true,
      scene: sceneId
    });
    return { ok: true, updatedCount: 1 };
  }

  if (act === 'power:on' || act === 'power:off') {
    return await setHueLights({
      bridgeIp: ip,
      username: key,
      selectedLights: hueCfg.selectedLights,
      on: act === 'power:on',
      brightness: act === 'power:on' ? Number(hueCfg.brightness ?? 80) : undefined
    });
  }

  if (act.startsWith('color:') || act.startsWith('flash:')) {
    const isFlash = act.startsWith('flash:');
    const hex = act.slice(isFlash ? 6 : 6);
    const lightsObj = await hueRequest(ip, `/api/${encodeURIComponent(key)}/lights`, 'GET');
    const ids = resolveHueLightIds(lightsObj, hueCfg.selectedLights);
    const hsb = hexToHueHsb(hex);
    const body = {
      on: true,
      hue: hsb.hue,
      sat: hsb.sat,
      bri: Math.max(40, Math.round(((Number(hueCfg.brightness ?? 85)) / 100) * 254)),
      ...(isFlash ? { alert: 'select' } : {})
    };
    let updated = 0;
    await Promise.all(
      ids.map(async (id) => {
        try {
          await hueRequest(ip, `/api/${encodeURIComponent(key)}/lights/${id}/state`, 'PUT', body, 2000);
          updated++;
        } catch (e) {}
      })
    );
    return { ok: updated > 0, updatedCount: updated };
  }

  return { ok: false, error: `Unbekannte Hue-Aktion: ${act}` };
}

let hueRevertTimer = null;

async function triggerHueForEvent(rawCfg, eventType) {
  const cfg = normalizeHueConfig(rawCfg);
  if (!cfg.enabled || !cfg.bridgeIp || !cfg.username) return { ok: false, skipped: true };
  const actionId = String(cfg.eventScenes?.[eventType] || '').trim();
  if (!actionId) return { ok: false, skipped: true };

  if (hueRevertTimer) {
    clearTimeout(hueRevertTimer);
    hueRevertTimer = null;
  }

  const res = await applyHueAction(cfg, actionId);
  const revertSec = Math.max(0, Number(cfg.revertAfterSec ?? 8));
  const fallback = String(cfg.eventScenes?.defaultScene || cfg.eventScenes?.streamStart || '').trim();
  if (
    res.ok &&
    revertSec > 0 &&
    fallback &&
    !['streamStart', 'streamStop', 'defaultScene'].includes(eventType) &&
    fallback !== actionId
  ) {
    hueRevertTimer = setTimeout(() => {
      applyHueAction(cfg, fallback).catch(() => {});
    }, revertSec * 1000);
  }
  return res;
}

